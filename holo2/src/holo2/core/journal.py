"""The journal: the fold's starting point, and its order (F-16).

`state = fold(inputs, code, ordering)`. Nothing in a state directory is
authoritative — the archive is the paper — so the durable record a
session keeps is not its state but the two things the fold cannot
re-derive: **where it started** and **in what order it committed**.

File layout, one text line each::

    {"magic":"holo2-journal","schema_version":7,"families":[...],
     "session_type":"SessionIdentity","session":{...}}
    >["payload",["tile",["0","3","4","K"]],"scan",["",""]]   <- a dispatch
    9f0c…64 hex…                                            <- its commit
    3a71…                                                   <- a commit

Line 1 is the STARTING POINT: schema version, the record-family manifest,
and the session identity BY VALUE (the format row id, the receiver
policy, the recipe entries, the ordered provider ids and the page domain
ride inside it — :class:`~holo2.engine.records.SessionIdentity` already
binds them, and core, which is generic over its registry's session
family, may not reach into that record's fields to re-state one of them).
It is the fold's left endpoint, written once at create and never again.

Every line after it is ONE ENTRY, of exactly two shapes.

A **COMMIT** is the content-derived batch id and nothing else. No
content, no keys, no counts, no clocks — the content is regenerated by
re-running the fold, and per-item determinism (L12: no clocks, seeded
draws only, value-bound policy) is what makes that regeneration
faithful. 65 bytes a commit is what makes the journal affordable at
every commit: it is appended and fsynced AT the commit, which is what
makes it the durable record and the cache merely a memo.

A **START MARKER** (``>`` + the dispatched work's identity, H4 W2's
second concurrency ruling) is the other half of the fold's ordering, and
it exists because commit order alone does not determine a pooled run. A
fire's inputs are fixed by its DISPATCH, not by its commit: it reads the
store as of the moment it was launched and lands, possibly, many commits
later. So the journal records the dispatch too, and **its POSITION IS
THE SNAPSHOT PREFIX** — the state a replay must launch that worker
against is exactly the fold of the entries before it. The marker carries
no payload beyond the work identity, because everything else about the
pass is a function of that state; markers FOLD TO NOTHING (the store
ignores them — they are ordering, not facts, so the no-no-op-facts
ruling stands untouched) and cost one small record per dispatched pass.

What that buys: the pooled DISPATCH ORDER stops being unrecorded.
Before markers, a replay re-derived proposals in whatever order its own
scheduler chose, which for a pooled recording was a different order — a
fire dispatched before a neighbouring commit and landing after it could
not be reproduced at all, and the tail refusal below is where it
surfaced. A marker with no matching commit replays as a NON-COMMITTING
pass, which is how a failed pull pass rebuilds the scheduler's in-memory
tried set and acceptance floor exactly.

WHAT IS AND IS NOT PROVEN (2026-08-16, stated so nobody reads more into
the mechanism than it has earned): the MECHANISM is pinned exactly, on
test doubles that stage the interleaving deliberately — a pooled
ordering replays byte-for-byte and its journal comes back entry for
entry, and the same ordering with its markers stripped (which is what a
pre-marker journal IS) fails loudly
(``holo2/tests/engine/test_replay.py``). Pooled crash-cut RECOVERY is
pinned the same way, and rests on the frame rule beside it — a cache
frame is a resume point, so it is taken only where no dispatch is
outstanding (``store._frame``). On the REAL provider stack the pooled
audit was improved but NOT closed: ``holo2/measure/test_pool_e2e.py``'s
byte-exact replay failed every run before markers and passed some runs
after them. That file was deleted with the measure cleanup and this
real-provider-stack measurement has no surviving holder — history has
the driver. The residue it found is a placement pass that re-proposes
differently at its recorded position, and it is unclosed work, not a
claim.

Two consumers, one file: crash recovery re-earns the tail past what the
cache covers, and the ``--replay`` audit re-runs a recorded ordering
whole. They are the same mechanism (F-24, subsumed) — auditing a state
directory IS re-folding its journal and comparing batch ids.

PRE-MARKER JOURNALS REFUSE at the schema gate, like any older state
(``store.SCHEMA_VERSION`` 6 -> 7). There is no migration and no
dual-mode reader: a pre-marker pooled journal cannot be replayed exactly
by construction, which is the whole reason markers exist, and a reader
that pretended otherwise would be claiming a guarantee it does not have.

Caveats the record keeps: replay-as-truth is CODE-VERSION pinned (a
journal carries a session across code changes; an old one is verifiable
only by the code that wrote it), and bit-determinism is machine-pinned
(same-machine proven by the gates, cross-machine unclaimed).
"""
from __future__ import annotations

import os
from pathlib import Path
from typing import IO, Any, Iterable, Sequence

from .codec import CodecError, canonical_json_bytes, parse_json_bytes
from .keys import MalformedKeyError, WorkId

JOURNAL_NAME = "journal"
JOURNAL_MAGIC = "holo2-journal"

#: A batch id is a SHA-256 rendering (``commit.batch_id``), so a COMMIT
#: line has exactly one legal shape and reading it back needs no schema.
_ID_DIGITS = frozenset("0123456789abcdef")
_ID_LENGTH = 64

#: A start marker's sentinel. Not a hex digit, so the two entry shapes
#: are told apart by the first byte and a line that is neither still
#: refuses with the message it always had.
MARKER_PREFIX = ">"


class JournalError(RuntimeError):
    """A journal that is not this build's, or is not a journal."""


class ReplayError(RuntimeError):
    """A recorded ordering could not be re-earned from the given proposals."""


def start_marker(work_id: WorkId) -> str:
    """The journal line one DISPATCH writes: its work identity, canonically.

    A ``WorkId`` is a STRUCTURE — family, subject key, route, scope — and
    ``to_json``/``from_json`` round-trip it exactly, which is what a
    marker needs and what its ``__str__`` (display, lossy) is not.
    """
    return MARKER_PREFIX + canonical_json_bytes(work_id.to_json()).decode()


def is_marker(entry: str) -> bool:
    return entry.startswith(MARKER_PREFIX)


def marker_work_id(entry: str) -> WorkId:
    """The work a start marker names. Raises on anything else."""
    if not is_marker(entry):
        raise JournalError(f"not a start marker: {entry!r}")
    try:
        return WorkId.from_json(parse_json_bytes(
            entry[len(MARKER_PREFIX):].encode()))
    except (CodecError, MalformedKeyError) as exc:
        raise JournalError(f"unreadable start marker: {exc}") from exc


def commit_count(entries: Iterable[str]) -> int:
    """How many of these entries are COMMITS — the store's own sequence."""
    return sum(1 for entry in entries if not is_marker(entry))


def position_after_commits(entries: Sequence[str], commits: int) -> int:
    """The entry index just past the ``commits``-th commit.

    Where a resume picks the journal up: the memo covers that many
    COMMITS, so everything past the last covered one is tail to re-earn.

    THERE IS NO "STRANDED MARKER" CASE for this index to miss: a cache
    frame is taken only where no dispatch is outstanding
    (``core.store._frame`` — a frame is a resume point), so every marker
    before the position a resume starts at has already settled — the
    memo's boundary is a clean cut through the dispatches by construction
    (``engine.replay._follow_recorded``'s own docstring states the
    invariant and why). The filter is exact in the direction that
    matters: a pass whose commit IS covered no longer arms at all,
    because the frontier does not offer finished work and the spend
    ledger holds its identity.
    """
    seen = 0
    for index, entry in enumerate(entries):
        if seen == commits:
            return index
        if not is_marker(entry):
            seen += 1
    return len(entries)


class ReplayCursor:
    """A recorded ordering, consumed in place — the audit AND the recovery.

    The cursor is the store's own JOURNAL POSITION (H4 W2: entries, not
    commits, because a start marker occupies one too), so *every* entry a
    run makes — a dispatch, a worker proposal, a subscription
    re-declaration, a close consult — is checked against the position it
    occupied in the recorded run. Divergence raises rather than silently
    producing a different state, which is the whole of "auditing a state
    directory is re-folding its journal and comparing batch ids".
    """

    def __init__(self, ordering: Iterable[str]) -> None:
        self.ordering = tuple(ordering)

    def at(self, position: int) -> str | None:
        """The entry recorded at ``position``, or None past the end."""
        return (self.ordering[position]
                if position < len(self.ordering) else None)

    def verify(self, position: int, batch_id: str) -> None:
        """Check the commit that just landed against the record.

        ``position`` is where it LANDED (the store advanced past it), so
        the entry to compare is the one before the cursor now stands at.
        """
        index = position - 1
        if index >= len(self.ordering):
            raise ReplayError(
                f"entry {index} ({batch_id}) runs past the recorded "
                f"ordering of {len(self.ordering)} entries")
        recorded = self.ordering[index]
        if recorded != batch_id:
            raise ReplayError(
                f"journal position {index}: replay proposed {batch_id}, the "
                f"recorded run wrote {recorded}")

    def exhausted(self, position: int) -> bool:
        return position >= len(self.ordering)


def _starting_point(line: bytes, path: Path) -> dict[str, Any]:
    """Line 1's own contract: it decodes, and it is an OBJECT.

    C5 review fix (2026-08-22). The two readers below answer different
    questions — "what IS this" reads one line, "what happened here" reads
    the file — but they meet on the same first line, and each carried its
    own copy of this parse and these two sentences. One drifting copy is
    the failure ``test_a_peek_refuses_what_an_open_would_refuse`` exists
    to prevent, and that pin compares OUTCOMES: a message or a parse
    moving in one reader alone would slip past it. So the shared half is
    stated once, here.

    What is NOT shared is each reader's precondition — a torn CREATE (no
    trailing newline on the only line there is) and an empty file are
    genuinely different discoveries, made with different reads, and they
    stay at their own call sites.
    """
    try:
        header = parse_json_bytes(line)
    except CodecError as exc:
        raise JournalError(f"{path}: unreadable starting point: {exc}") from exc
    if not isinstance(header, dict):
        raise JournalError(f"{path}: the starting point is not an object")
    return header


def read_starting_point(path: Path) -> dict[str, Any]:
    """LINE 1 ALONE: what this session was started as, without its order.

    The read half of the read-first surface (C5, 2026-08-22, RULINGS G6;
    ``core.store.Store.peek_identity`` is the gate that types it).
    :func:`read_journal` answers "what happened here", which means
    reading the whole file; this answers "what IS this", which is one
    line and must stay one line — a caller deciding whether it may
    resume a multi-gigabyte state should not pay for the ordering to
    find out.

    **No lock, and that is a property of the file rather than a
    shortcut.** Line 1 is written once, by :meth:`Journal.create`, and
    never rewritten — every later write is an APPEND past it
    (:meth:`Journal.append`). So a live writer cannot tear it and a
    reader needs no claim on the directory, where taking the exclusive
    lock would make a read-only question refuse exactly while a decode
    is running, which is when an operator asks it.

    A starting point without its trailing newline is a TORN CREATE: the
    same tail rule :func:`read_journal` applies to a commit id, at the
    one line that has no re-earn behind it. There is no session here
    yet, and it says so rather than parsing a fragment.
    """
    try:
        with open(path, "rb") as handle:
            line = handle.readline()
    except OSError as exc:
        raise JournalError(f"{path}: no journal ({exc})") from exc
    if not line.endswith(b"\n"):
        raise JournalError(f"{path}: journal holds no starting point")
    return _starting_point(line[:-1], path)


def read_journal(path: Path) -> tuple[dict[str, Any], tuple[str, ...]]:
    """The starting point and the recorded ordering, read back.

    A final line without its newline is a torn tail — a crash between the
    write and the fsync — and is dropped: the commit it named never became
    durable, and its work re-arms like any other lost in-flight work.
    """
    if not path.is_file():
        raise JournalError(f"{path}: no journal")
    lines = path.read_bytes().split(b"\n")
    lines.pop()          # the tail past the last newline: empty, or torn
    if not lines:
        raise JournalError(f"{path}: journal holds no starting point")
    header = _starting_point(lines[0], path)
    ordering: list[str] = []
    for number, line in enumerate(lines[1:], start=2):
        text = line.decode("utf-8", "replace")
        if is_marker(text):
            marker_work_id(text)          # shape-checked at read, like an id
        elif len(text) != _ID_LENGTH or not set(text) <= _ID_DIGITS:
            raise JournalError(
                f"{path}: line {number} is not a batch id: {text!r}")
        ordering.append(text)
    return header, tuple(ordering)


class Journal:
    """One session's ordering record, open for append.

    The handle stays open for the life of the session: a commit pays one
    ``write`` and one ``fsync``, not an open/close pair, and the ordering
    is the only durable thing the commit path writes.
    """

    def __init__(self, path: Path, header: dict[str, Any],
                 ordering: Iterable[str], handle: IO[bytes], *,
                 start: int, fsync: bool = True) -> None:
        self._path = path
        self._header = header
        self._ordering = list(ordering)
        self._handle = handle
        # Where the ordering begins in the file. Every line after it is
        # one id of fixed width, so the offset of position *p* is
        self._start = start
        self._fsync = fsync

    @classmethod
    def create(cls, path: Path, header: dict[str, Any], *,
               fsync: bool = True) -> "Journal":
        """Write the starting point into a fresh journal."""
        line = canonical_json_bytes(header) + b"\n"
        with open(path, "xb") as handle:
            handle.write(line)
            handle.flush()
            if fsync:
                os.fsync(handle.fileno())
        return cls(path, header, (), open(path, "ab"), start=len(line),
                   fsync=fsync)

    @classmethod
    def resume(cls, path: Path, header: dict[str, Any],
               ordering: Iterable[str], *, fsync: bool = True) -> "Journal":
        """Continue an already-read journal (see :func:`read_journal`)."""
        with open(path, "rb") as handle:
            start = len(handle.readline())    # the starting point, as written
        return cls(path, header, ordering, open(path, "ab"), start=start,
                   fsync=fsync)

    @property
    def path(self) -> Path:
        return self._path

    @property
    def header(self) -> dict[str, Any]:
        """The starting point this session was written under."""
        return self._header

    def ordering(self) -> tuple[str, ...]:
        """Every recorded ENTRY — dispatches and commits — in order."""
        return tuple(self._ordering)

    def append(self, entry: str, position: int) -> None:
        """Record one entry — a commit id or a start marker — at ``position``.

        Both shapes take this one path, because both are the fold's order
        and the tail law below is about ORDER, not about what an entry
        means. A dispatch is recorded exactly as a commit is: written and
        fsynced where it happened, never rewritten.

        A journal may already hold this position: a crash leaves commits
        recorded whose results the cache never memoised, and the run that
        re-earns them re-derives the same batches. An id that AGREES with
        what stands there is not written again — the record already says
        it. An id that DISAGREES is REFUSED, loudly (integrator ruling
        2026-08-14, overruling the first cut's silent truncation): the
        journal is the AUTHORITATIVE history, and rewriting its tail
        because this run's inputs re-derived differently — a capture
        missing, a capture added, code moved — would quietly erase the
        record that those commits happened. The entries past the memo
        describe work that never became durable STATE, but the journal is
        not state; it is the fold's order, and the one thing it promises
        is that it is never rewritten. The remedy is the operator's,
        explicitly: provide the inputs that produced the tail, or delete
        the state directory (the cache doctrine's honest reset). The
        invariant kept: the journal's first entries ARE this session's
        own, in the order they happened, forever.
        """
        if not is_marker(entry) and (
                len(entry) != _ID_LENGTH or not set(entry) <= _ID_DIGITS):
            raise JournalError(f"not a batch id: {entry!r}")
        if position < len(self._ordering):
            if self._ordering[position] == entry:
                return                        # re-earned: the record stands
            raise JournalError(
                f"journal position {position} records "
                f"{self._ordering[position]} and this fold derived "
                f"{entry}: the provided inputs cannot reproduce the "
                f"recorded tail ({len(self._ordering) - position} "
                "entries). Provide the inputs that produced it, or "
                "delete the state directory and re-decode.")
        self._handle.write(entry.encode("utf-8") + b"\n")
        self._handle.flush()
        if self._fsync:
            os.fsync(self._handle.fileno())
        self._ordering.append(entry)

    def close(self) -> None:
        self._handle.close()

    def __len__(self) -> int:
        return len(self._ordering)


