#!/usr/bin/env python
"""THE CROP-CASES CENSUS — rendering, split out of ``crop_cases.py``
(HANDOFF-CROP Deliverable A, the 1,000-line seam signal).

NOT A TEST and not a driver: import-only, the rendering half of the
crop-case generator. ``crop_cases.py`` computes the class sets, fits the
affine, clusters/splits/halos the targets and writes the manifest +
crops; this module turns the finished ``SheetResult`` (the same object
the generator holds) into the census markdown, and knows nothing else.
The seam is ``parity_k_report.py``'s / ``crop_harness_report.py``'s,
taken now that ``crop_cases.py`` crossed 1,000 lines: this module
imports NOTHING from ``crop_cases`` — ``result`` arrives duck-typed
(the pattern ``parity_k_report.py`` set: rows/results arrive as plain
data, never a re-import of the declaring module), and the two constants
the rendering text quotes (``PX_PAD_CELLS``, ``CONTROL_RIM_CELLS``) are
PARAMETERS of :func:`render_census` rather than re-declared literals —
they are behavioural constants that size the geometry, not a cosmetic
rendering order, so duplicating them as bare numbers here would let the
two modules silently disagree if either changed. Nothing here reads a
state, opens a capture or touches the corpus — pure formatting of
already-computed fields.
"""
from __future__ import annotations

from typing import Any


def render_census(result: Any, *, merge_gap_tiles: int, max_span_cells: int,
                  px_pad_cells: int, control_rim_cells: int) -> str:
    spec = result.spec
    classes = result.classes
    manifest = result.manifest
    lines = [f"# Crop cases — {spec.label}", ""]
    lines.append(f"Generated by `holo2/measure/crop_cases.py` on tree "
                 f"`{manifest['generator']['tree'][:12]}`"
                 + (" (dirty)" if manifest["generator"]["dirty_sha"]
                    else " (clean)")
                 + f", wall {result.wall_s:.1f} s. Capture "
                 f"`{spec.capture_path}` "
                 f"({result.capture_shape_yx[0]}x"
                 f"{result.capture_shape_yx[1]} px, sha "
                 f"`{manifest['capture_sha256'][:12]}…`, verified against "
                 f"the v1 state's authenticated source).")
    lines.append("")
    lines.append("## Certificate sets and discovery")
    lines.append("")
    lines.append("- v1 state: `%s`" % spec.v1_state)
    for name, disc in (("pre-F1/F2", result.pre_discovery),
                       ("F2", result.f2_discovery)):
        lines.append(f"- holo2 {name} ({len(disc.certified)} certificates, "
                     + ("state-recomputed" if disc.chosen is not None
                        else "markdown-derived") + "):")
        for row in disc.trail:
            lines.append(f"  - {row}")
    lines.append("")
    lines.append("## Target classes (cross-checked against the recorded "
                 "headers)")
    lines.append("")
    lines.append("| class | count | note |")
    lines.append("|---|---:|---|")
    raw_flip = len(classes.flipped) + len(classes.raw_flip_overlap)
    lines.append(f"| flipped | {len(classes.flipped)} | raw pre→F2 flips "
                 f"{raw_flip}; {len(classes.raw_flip_overlap)} of them "
                 f"({sorted(classes.raw_flip_overlap)}) are classed "
                 f"v1_missing — the disjointness ruling in the module "
                 f"docstring |")
    lines.append(f"| still_missing_v2 | {len(classes.still_missing_v2)} | "
                 f"= recorded F2 \"v1 has, holo2 lacks\" |")
    lines.append(f"| v1_missing | {len(classes.v1_missing)} | = recorded "
                 f"F2 \"holo2 has, v1 lacks\" |")
    lines.append(f"| neither | {len(classes.neither)} | = recorded F2 "
                 f"\"neither certifies\" |")
    lines.append(f"| TARGETS | {len(classes.targets)} | each in exactly "
                 f"one case (asserted) |")
    lines.append(f"| both certified | {result.n_both} | the control "
                 f"population (minus the {len(classes.flipped)} flipped "
                 f"targets it contains) |")
    lines.append("")
    lines.append("## Geometry")
    lines.append("")
    lines.append(f"- global affine (x-first rows): "
                 f"{manifest['affine_cell_to_px']}")
    lines.append(f"- fitted from {result.affine.n_poses} accepted v1 poses "
                 f"(5 points each); |residual| median "
                 f"{result.affine.residual_median_px:.1f} px, p99 "
                 f"{result.affine.residual_p99_px:.1f} px, max "
                 f"{result.affine.residual_max_px:.1f} px "
                 f"(≈{result.affine.residual_max_px / result.affine.px_per_cell:.1f} "
                 f"cells — absorbed by the {px_pad_cells}-cell pixel pad)")
    lines.append(f"- px/cell {result.affine.px_per_cell:.3f}; halo "
                 f"{manifest['halo_cells']} cells; merge gap "
                 f"{merge_gap_tiles} tiles; max span {max_span_cells} "
                 f"cells; control rim {control_rim_cells} cells")
    lines.append("")
    lines.append("## Cases")
    lines.append("")
    lines.append("| case | targets (by class) | cell bbox [x0,y0,x1,y1] | "
                 "px bbox [x0,y0,x1,y1] | px size | MB | controls |")
    lines.append("|---|---|---|---|---|---:|---:|")
    total_mb = 0.0
    for case in manifest["cases"]:
        by_class: dict[str, int] = {}
        for target in case["targets"]:
            for name in target["classes"]:
                by_class[name] = by_class.get(name, 0) + 1
        tally = ", ".join(f"{v} {k}" for k, v in sorted(by_class.items()))
        px0, py0, px1, py1 = case["px_bbox"]
        mb = result.sizes_mb.get(case["case_id"], 0.0)
        total_mb += mb
        lines.append(f"| {case['case_id']} | {len(case['targets'])} "
                     f"({tally}) | {case['cell_bbox']} | {case['px_bbox']} "
                     f"| {px1 - px0}x{py1 - py0} | {mb:.0f} | "
                     f"{len(case['controls'])} |")
    lines.append("")
    lines.append(f"{len(manifest['cases'])} cases, "
                 f"{sum(len(c['targets']) for c in manifest['cases'])} "
                 f"targets, {total_mb / 1e3:.2f} GB of crops.")
    lines.append("")
    return "\n".join(lines)
