"""rebuild_v2.py -- regenerate the candidate print of record v2 of the
bootstrap (stages 1-3; the fixed point of ruling 60's convergence,
CONVERGENCE-2026-10-23.md, re-run on the repaired c.py in
CONVERGENCE-2026-10-23b.md) from the committed texts and frozen spellings.

The texts (read, never written): stage1/template.py, stage1/frozen_lower.json
and frozen_upper.json (the frozen spellings of stage1/search.py; the searches
are NOT run here), r2reader/reader_lite_v1.py (b.py's text, its N2 / B2
tokens), stage3/c.py (the R2 content, generated by stage3/make_c_cv.py at the
fixed point; the generation is a search and is not run here).  The stage-3
volume (the 15 holo K pages of c3-k-r0547@35x24 carrying the release, the
record's T1 container) is an INPUT, stage3/e2e_c.py volume's output, checked
page by page against its manifest and imagemasks.

Steps, into OUT (default bootstrap/build/sheets/):
  1. stage 1, both cases, c.py as the content: stage1/chain_v2.py make CASE
     (stage1/make_typed.py: the fixed point, the frontier at the record's
     page bound, the proofs, the second byte-compared build) into OUT/stage1/;
  2. the R2 pages, both cases: stage1/chain_v2.py pages CASE (e2e.py's page
     step: payload, r2/gen.py pages, verify_grid, the nominal renders);
  3. the sheets: stage1/make_sheets_v2.py (stages1-2-listing-data-upper.pdf,
     stage3-r2-pages.pdf, stage4-archive-pages.pdf, chain-DATE.pdf, and the
     for-print print-DATE.pdf of ruling 62 through stage1/print_sheets.py --
     its QR codes read from stage1/qr/, no QR library needed, refused if
     a.py or data.txt moved; the stage-4 pages headed in the left margin,
     their headed PostScript in OUT/stage4-ps/; previews, MANIFEST.txt; every
     1-bit page round-tripped through ghostscript pixel-exact);
  4. OUT/SHA256SUMS: every file the steps wrote that the print is made of.
A run that finds a MANIFEST.txt from an earlier run in OUT asserts that the
new one is byte-identical (and prints the diff if not); --twice runs the whole
rebuild twice and asserts the same.  Not touched: bootstrap/build.py,
bootstrap/loader/ (the print of record of 2026-10-20).

  env/bin/python bootstrap/rebuild_v2.py [--out DIR] [--vol DIR] [--date D] [--twice]
"""
import difflib
import hashlib
import os
import shutil
import subprocess
import sys

BOOT = os.path.dirname(os.path.abspath(__file__))
PY = 'env/bin/python'
TEXTS = ['stage1/template.py', 'stage1/frozen_lower.json', 'stage1/frozen_upper.json',
         'r2reader/reader_lite_v1.py', 'stage3/c.py', 'stage1/qr/qr-a.pbm', 'stage1/qr/qr-d.pbm']


def arg(name, default=None):
    a = sys.argv
    return a[a.index(name) + 1] if name in a else default


OUT = os.path.abspath(arg('--out', os.path.join(BOOT, 'build', 'sheets')))
VOL = os.path.abspath(arg('--vol', os.path.join(BOOT, 'build', 'stage3', 'e2e', 'T1', 'vol')))
DATE = arg('--date', '2026-10-23')


def sha(p):
    return hashlib.sha256(open(p, 'rb').read()).hexdigest()


def step(label, cmd):
    log = os.path.join(OUT, 'logs', label + '.out')
    with open(log, 'w') as f:
        r = subprocess.run(cmd, stdout=f, stderr=subprocess.STDOUT, cwd=BOOT)
    tail = open(log).read().strip().split('\n')[-3:]
    print(f'{label}: exit {r.returncode}  ' + ' | '.join(t[:160] for t in tail), flush=True)
    if r.returncode:
        raise SystemExit(f'{label} failed, see {log}')


def once():
    s1 = os.path.join(OUT, 'stage1')
    shutil.rmtree(s1, ignore_errors=True)
    os.makedirs(os.path.join(OUT, 'logs'), exist_ok=True)
    print('texts: ' + '; '.join(f'{t} {sha(os.path.join(BOOT, t))[:16]}' for t in TEXTS), flush=True)
    for case in ('lower', 'upper'):
        step(f'make-{case}', [PY, os.path.join(BOOT, 'stage1', 'chain_v2.py'), 'make', case, '--tree', BOOT,
                              '--out', s1])
        step(f'pages-{case}', [PY, os.path.join(BOOT, 'stage1', 'chain_v2.py'), 'pages', case, '--tree', BOOT,
                               '--out', s1])
    step('sheets', [PY, os.path.join(BOOT, 'stage1', 'make_sheets_v2.py'), '--s1', s1, '--vol', VOL, '--out', OUT,
                    '--date', DATE])
    files = [os.path.join(OUT, f) for f in sorted(os.listdir(OUT))
             if f.endswith(('.pdf', '.png')) or f == 'MANIFEST.txt']
    files += [os.path.join(OUT, 'stage4-ps', f) for f in sorted(os.listdir(os.path.join(OUT, 'stage4-ps')))]
    for case in ('lower', 'upper'):
        d = os.path.join(s1, case)
        files += [os.path.join(d, f) for f in ('a.py', 'data.txt', 'codes.txt', 'b.py', 'readable.py', 'sizes.txt',
                                               'leaf3.txt', 'leaf4.txt', 'leaves.pdf') if os.path.exists(os.path.join(d, f))]
        files += sorted(os.path.join(d, 'r2', f) for f in os.listdir(os.path.join(d, 'r2'))
                        if f == 'payload.bin' or f.endswith(('.pbm', '.grid.txt')))
    sums = ''.join(f'{sha(p)}  {os.path.relpath(p, OUT)}\n' for p in files)
    open(os.path.join(OUT, 'SHA256SUMS'), 'w').write(sums)
    return open(os.path.join(OUT, 'MANIFEST.txt')).read(), sums


def compare(prev, new, what):
    if prev == new:
        print(f'{what}: byte-identical to the previous run')
        return True
    print(f'{what} DIFFERS from the previous run:')
    sys.stdout.writelines(difflib.unified_diff(prev.splitlines(True), new.splitlines(True), 'previous', 'this run'))
    return False


def main():
    os.makedirs(OUT, exist_ok=True)
    mp, sp = os.path.join(OUT, 'MANIFEST.txt'), os.path.join(OUT, 'SHA256SUMS')
    prev = (open(mp).read(), open(sp).read() if os.path.exists(sp) else None) if os.path.exists(mp) else None
    runs = 2 if '--twice' in sys.argv else 1
    ok = True
    for i in range(runs):
        new = once()
        if prev is not None:
            ok &= compare(prev[0], new[0], 'MANIFEST.txt')
            if prev[1] is not None:
                ok &= compare(prev[1], new[1], 'SHA256SUMS')
        prev = new
    print(new[0])
    assert ok, 'the rebuild is not byte-identical to the previous run'


if __name__ == '__main__':
    main()
