"""Write the cm2-family decoders (candidates A and B) from one set of parts,
so the model is the same text in every file (harness only).

  model  x = exact context map (a dict; memory grows with the input)
         h = bounded: 2^24 slots named by a hash of cm2's exact key, the slot
             keeps the key, a different key evicts it (counts back to 0, 0)
  coder  rc   = the 10-18 carry-less 32-bit range coder (typed/cm2_v1_dec.py),
                12-bit probability
         rans = rANS with a bounded state (x in [2^23, 2^31), byte
                renormalisation), the same 12-bit probability
         blk  = the v2 big-integer rANS with the EXACT weights (no 12-bit
                rounding), restarted every 65,536 output bytes so each
                block's integer stays small: linear time
  orders v2 = (0, 1, 2, 3, 4, 6, 8, 12, 16) (typed/cm2_dec.py), v1 = (0, 1,
         2, 3, 4, 6, 8, 12) (typed/cm2_v1_dec.py)
Files: dec_cm2{x,h}{rc,rans,blk}.py (+ dec_cm2xrc1.py, v1 orders) and the
matching enc_*.py (derive_cm2.make_encoder over the decoder's text)."""
from pathlib import Path

HERE = Path(__file__).resolve().parent

DOC = {
    "x": "cm2's count-mixing model with its EXACT context map (a Python dict: "
         "memory grows with the input, about 4 KB per input byte)",
    "h": "cm2's count-mixing model with BOUNDED memory: 2^24 counter-pair slots, "
         "each named by a hash of cm2's exact key and keeping that key (a "
         "different key evicts it, counts back to 0, 0)",
    "rc": "the 10-18 carry-less 32-bit range coder (typed/cm2_v1_dec.py), "
          "12-bit probability",
    "rans": "rANS with a bounded state (x in [2^23, 2^31), byte "
            "renormalisation), 12-bit probability",
    "blk": "the v2 big-integer rANS with the exact weights, restarted every "
           "65,536 output bytes (3-byte length + the block's integer); "
           "linear time",
}

HEAD = {
    "rc": "  M = 4294967295\n  a, b, x, k = 0, M, int.from_bytes(s[:4], 'big'), 4\n",
    "rans": "  x, k = int.from_bytes(s[:4], 'big'), 4\n",
    "blk": "  x, k = 0, 0\n",
}

MODEL = {
    "x": ("  t = {}\n",
          "      cs = [t.setdefault((h & q | q + 1) << 8 | c0, [0, 0]) for q in ms]\n"
          "      s1 = 1 + sum(c[1] << (c[0] == 0) << w for w, c in enumerate(cs))\n"
          "      s0 = 1 + sum(c[0] << (c[1] == 0) << w for w, c in enumerate(cs))\n",
          "      for c in cs:\n"
          "        c[y], c[1 - y] = c[y] + 1, min(c[1 - y], c[1 - y] // 4 + 2)\n"),
    "h": ("  E = (1 << 24) - 1\n  K, C = [0] * (E + 1), [0] * (2 * E + 2)\n",
          "      cs = []\n"
          "      for q in ms:\n"
          "        g = (h & q | q + 1) << 8 | c0\n"
          "        e = hash(g) * 0x9E3779B97F4A7C15 >> 40 & E\n"
          "        if K[e] != g:\n"
          "          K[e], C[2 * e], C[2 * e + 1] = g, 0, 0\n"
          "        cs.append(2 * e)\n"
          "      s1 = 1 + sum(C[c + 1] << (C[c] == 0) << w for w, c in enumerate(cs))\n"
          "      s0 = 1 + sum(C[c] << (C[c + 1] == 0) << w for w, c in enumerate(cs))\n",
          "      for c in cs:\n"
          "        C[c + y], C[c + 1 - y] = C[c + y] + 1, min(C[c + 1 - y], C[c + 1 - y] // 4 + 2)\n"),
}

CODER = {
    "rc": "      xm = a + (b - a >> 12) * (s1 * 4094 // (s0 + s1) + 1)\n"
          "      y = x <= xm\n"
          "      a, b = (a, xm) if y else (xm + 1, b)\n"
          "      while a >> 24 == b >> 24:\n"
          "        a, b, x, k = a << 8 & M, b << 8 & M | 255, x << 8 & M | s[k], k + 1\n",
    "rans": "      p, r = s1 * 4094 // (s0 + s1) + 1, x & 4095\n"
            "      y = r < p\n"
            "      x = (p if y else 4096 - p) * (x >> 12) + r - (0 if y else p)\n"
            "      while x < 8388608:\n"
            "        x, k = x << 8 | s[k], k + 1\n",
    "blk": "      if j == 0 == i % 65536:\n"
           "        L, k = int.from_bytes(s[k:k + 3], 'big'), k + 3\n"
           "        x, k = int.from_bytes(s[k:k + L], 'big'), k + L\n"
           "      f, r = divmod(x, s0 + s1)\n"
           "      y = r >= s0\n"
           "      x = f * (s1 if y else s0) + r - s0 * y\n",
}

TEMPLATE = '''"""{title}: {model}; {coderdoc}.  Orders {orders}.
Container: 4-byte big-endian n + the coder's bytes.  Generated by
gen_cm2fam.py."""
# BEGIN DECODER
def unz(s):
  n, s, D = int.from_bytes(s[:4], 'big'), s[4:] + bytes(4), {D}
  ms = [(1 << 8 * o) - 1 for o in {orders}]
{mhead}  buf = bytearray(D + n)
{head}  for i in range(n):
    c0, h = 1, int.from_bytes(buf[i:i + D], 'big')
    for j in range(8):
{mpred}      # CODER
{coder}      # /CODER
{mupd}      c0 = c0 * 2 + y
    buf[D + i] = c0 & 255
  return bytes(buf[D:])
# END DECODER
'''

ENC = '''"""Encoder for {dec}: derived from the decoder's text (derive_cm2.py)."""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import derive_cm2  # noqa: E402

enc = derive_cm2.make_encoder(str(HERE / "{dec}"), "{coder}")
'''

TITLES = {"xrc": "Candidate A", "xrc1": "Candidate A (v1 orders)", "hrc": "Candidate A-h",
          "xrans": "Candidate B-state", "hrans": "Candidate B-state-h",
          "xblk": "Candidate B-blocks", "hblk": "Candidate B-blocks-h"}


def main():
    for name, title in TITLES.items():
        m, c = name[0], name[1:].rstrip("1")
        orders = "(0, 1, 2, 3, 4, 6, 8, 12)" if name.endswith("1") else "(0, 1, 2, 3, 4, 6, 8, 12, 16)"
        mhead, mpred, mupd = MODEL[m]
        text = TEMPLATE.format(title=title, model=DOC[m], coderdoc=DOC[c], orders=orders,
                               D=12 if name.endswith("1") else 16, mhead=mhead, head=HEAD[c],
                               mpred=mpred, coder=CODER[c], mupd=mupd)
        dec = "dec_cm2%s.py" % name
        (HERE / dec).write_text(text)
        (HERE / ("enc_cm2%s.py" % name)).write_text(ENC.format(dec=dec, coder=c))
        compile(text, dec, "exec")
        print(dec)


if __name__ == "__main__":
    main()
