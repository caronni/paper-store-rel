_OPEN, _CLOSE = '([{', ')]}'
_LEADS = frozenset(('for', 'if', 'else', 'and', 'or', 'not', 'in', 'is', '+', '-', '*', '//',
                    '%', '|', '^', '&', '<<', '>>', '<', '>', '==', '>=', '<=', '!='))
_COMPARE = frozenset(('<', '>', '==', '>=', '<=', '!=', 'in', 'is'))
_BINARY = (('|',), ('^',), ('&',), ('<<', '>>'), ('+', '-'), ('*', '//', '%', '@', '/'))


def _tokens(text):
    """The tokens of one line of code: [(type, string, start column, end column)]."""
    out = []
    for t in tokenize.generate_tokens(io.StringIO(text).readline):
        if t.type in (tokenize.NEWLINE, tokenize.NL, tokenize.ENDMARKER, tokenize.INDENT,
                      tokenize.DEDENT, tokenize.COMMENT):
            continue
        assert t.start[0] == t.end[0] == 1, f'one line expected: {text!r}'
        out.append((t.type, t.string, t.start[1], t.end[1]))
    return out


def _depths(toks):
    """The bracket depth at each token; both brackets of a group sit at the
    depth outside it."""
    d, out = 0, []
    for _, s, _, _ in toks:
        if s in _CLOSE:
            d -= 1
        out.append(d)
        if s in _OPEN:
            d += 1
    return out


def _matches(toks):
    match, stack = {}, []
    for i, (_, s, _, _) in enumerate(toks):
        if s in _OPEN:
            stack.append(i)
        elif s in _CLOSE:
            match[stack.pop()] = i
    return match


def _groups(toks):
    """The top-level bracket groups: [(index of the opening, of the closing token)]."""
    dep = _depths(toks)
    return sorted((j, i) for j, i in _matches(toks).items() if dep[j] == 0)


def _norm(dump):
    return dump.replace('ctx=Store()', 'ctx=Load()')


def _respell(text):
    """SPELL's literal spellings (the same value)."""
    for typ, s, a, b in reversed(_tokens(text)):
        if typ == tokenize.NUMBER and s.isdigit() and int(s) in SPELL:
            text = text[:a] + SPELL[int(s)] + text[b:]
    return text


def _same(text, node):
    try:
        got = ast.parse(text, mode='eval').body
    except SyntaxError:
        return False
    return _norm(ast.dump(got)) == _norm(ast.dump(node))


def _drop_redundant_parens(text, node):
    """Drop every pair of parentheses that is not a call's and whose removal
    leaves the ast unchanged (ast.unparse doubles the parentheses of a sole
    generator argument and parenthesises a comparison in a comprehension's
    condition); each removal is checked by parsing."""
    start = 0
    while True:
        toks = _tokens(text)
        for j, i in sorted(_matches(toks).items()):
            if toks[j][1] != '(' or toks[j][2] < start or i == j + 1:
                continue
            if j and ((toks[j - 1][0] == tokenize.NAME and not keyword.iskeyword(toks[j - 1][1]))
                      or toks[j - 1][1] in _CLOSE):
                continue                                # a call's parentheses
            a, b = toks[j][2], toks[i][2]
            cand = text[:a] + text[a + 1:b] + text[b + 1:]
            if _same(cand, node):
                text, start = cand, a
                break
        else:
            return text


def expr(node):
    """An expression as text: ast.unparse, its redundant parentheses dropped,
    SPELL applied; checked to parse back to the same ast."""
    s = ast.unparse(node)
    t = _respell(_drop_redundant_parens(s, node))
    if not _same(t, node):
        raise AssertionError(f'the tidying changed an expression: {s!r} -> {t!r}')
    return t


def bare(node):
    """expr(), and a tuple without its outer parentheses (an assignment's
    targets and value, a return value, a loop target)."""
    s = expr(node)
    if isinstance(node, ast.Tuple) and node.elts and s[:1] == '(':
        toks = _tokens(s)
        if _groups(toks) == [(0, len(toks) - 1)]:
            if _same(s[1:-1], node):
                return s[1:-1]
    return s


def _binary(toks, i):
    if i == 0:
        return False
    typ, s = toks[i - 1][0], toks[i - 1][1]
    return (typ in (tokenize.NUMBER, tokenize.STRING) or s in _CLOSE
            or (typ == tokenize.NAME and (not keyword.iskeyword(s) or s in ('True', 'False', 'None'))))


def _cut(text, cols):
    cols = [c for c in cols if 0 < c < len(text)]
    pieces = [text[a:b].strip() for a, b in zip([0] + cols, cols + [len(text)])]
    return [p for p in pieces if p]


def _split(text, toks=None):
    """A fragment cut at its lowest-binding top-level delimiters: comprehension
    clauses, commas, colons (a slice, a dict item), a conditional expression,
    or, and, comparisons, then the binary operators by priority.  A leading keyword or operator of the
    fragment ('for ...', 'and ...', '+ ...') and a trailing comma are no
    delimiters.  -> (kind, pieces), kind None when nothing cuts."""
    toks = _tokens(text) if toks is None else toks
    dep = _depths(toks)
    lead = 1 if toks and toks[0][1] in _LEADS else 0
    end = len(toks) - 1 if toks and toks[-1][1] == ',' else len(toks)
    top = [i for i in range(lead, end) if dep[i] == 0]
    word = lambda i: toks[i][1]                                    # noqa: E731
    levels = []
    fors = [i for i in top if word(i) == 'for']
    if fors:
        levels.append(('comp', [toks[i][2] for i in
                                sorted(fors + [i for i in top if word(i) == 'if' and i > fors[0]])]))
    levels.append(('comma', [toks[i][3] for i in top if word(i) == ',']))
    levels.append(('colon', [toks[i][3] for i in top if word(i) == ':']))
    for kind, words in (('ternary', ('if', 'else')), ('or', ('or',)), ('and', ('and',))):
        levels.append((kind, [toks[i][2] for i in top if word(i) in words]))
    compare = [i for i in top if (word(i) in _COMPARE and not (word(i) == 'in' and word(i - 1) == 'not'))
               or (word(i) == 'not' and i + 1 < len(toks) and word(i + 1) == 'in')]
    levels.append(('compare', [toks[i][2] for i in compare if not (word(i) == 'not' and word(i - 1) == 'is')]))
    for ops in _BINARY:
        levels.append((ops[0], [toks[i][2] for i in top if word(i) in ops and _binary(toks, i)]))
    for kind, cols in levels:
        pieces = _cut(text, cols)
        if len(pieces) > 1:
            return kind, pieces
    return None, [text]


def _fits(depth, text):
    return len(INDENT) * depth + len(text) <= WIDTH


def _widest(text, toks):
    """The widest non-empty top-level bracket group: (head, body, tail) or None."""
    groups = [(j, i) for j, i in _groups(toks) if i > j + 1]
    if not groups:
        return None
    j, i = max(groups, key=lambda g: (toks[g[1]][2] - toks[g[0]][2], g[0]))
    o, c = toks[j][2], toks[i][2]
    return text[:o + 1], text[o + 1:c], text[c:]


def _group_split(text, depth, parts=None):
    """Break text at its widest top-level bracket group: the head through the
    opening bracket, the content one level deeper (on one line if it fits,
    else cut by _split), the closing bracket and the rest."""
    parts = parts or _widest(text, _tokens(text))
    if parts is None:
        return [INDENT * depth + text]
    head, body, tail = parts
    if _fits(depth + 1, body):
        inner = [INDENT * (depth + 1) + body]
    else:
        inner = []
        for p in _split(body)[1]:
            inner += _wrap_piece(p, depth + 1)
    return [INDENT * depth + head] + inner + [INDENT * depth + tail]


def _wrap_piece(text, depth):
    """One piece of a cut, on one line if it fits.  Else broken at its widest
    bracket group when that group holds half the piece or more and the head
    and the tail fit; else cut again at its own delimiters, at the same depth
    (an operator leads its line), unless it is a 'for' clause; else broken at
    its widest group."""
    if _fits(depth, text):
        return [INDENT * depth + text]
    toks = _tokens(text)
    parts = _widest(text, toks)
    if parts and 2 * len(parts[1]) >= len(text) and _fits(depth, parts[0]) and _fits(depth, parts[2]):
        return _group_split(text, depth, parts)
    if toks and toks[0][1] != 'for':
        kind, pieces = _split(text, toks)
        if kind is not None:
            out = []
            for p in pieces:
                out += _wrap_piece(p, depth)
            return out
    return _group_split(text, depth, parts)


def wrap(prefix, body, suffix, depth):
    """A statement prefix + body + suffix on one line if it fits.  Else a body
    with top-level delimiters is put in parentheses (the same ast): a tuple
    that fits on the next line goes there whole, anything else is cut, one
    piece per line; a body without delimiters is broken at its widest
    bracket group."""
    line = prefix + body + suffix
    if _fits(depth, line) or not body:
        return [INDENT * depth + line]
    toks = _tokens(body)
    kind, pieces = _split(body, toks)
    if kind == 'comma' and _fits(depth + 1, body):
        return [INDENT * depth + prefix + '(', INDENT * (depth + 1) + body, INDENT * depth + ')' + suffix]
    if kind is not None:
        out = [INDENT * depth + prefix + '(']
        for p in pieces:
            out += _wrap_piece(p, depth + 1)
        return out + [INDENT * depth + ')' + suffix]
    lines = _group_split(body, depth)
    lines[0] = INDENT * depth + prefix + lines[0][len(INDENT) * depth:]
    lines[-1] += suffix
    return lines


# ---- statements, comments, the file -----------------------------------------

_AUG = {ast.Add: '+', ast.Sub: '-', ast.BitXor: '^', ast.BitOr: '|', ast.BitAnd: '&',
        ast.Mult: '*', ast.FloorDiv: '//', ast.Mod: '%', ast.LShift: '<<', ast.RShift: '>>'}


def _plain(node):
    s = ast.unparse(node)
    if isinstance(node, ast.Tuple) and s[:1] == '(' and s[-1:] == ')':
        return s[1:-1]
    return s


def _head(s):
    """A statement's key text in role terms (the template's names)."""
    if isinstance(s, ast.Assign):
        return ' = '.join(_plain(t) for t in s.targets) + ' ='
    if isinstance(s, ast.AugAssign):
        return f'{_plain(s.target)} {_AUG[type(s.op)]}='
    if isinstance(s, ast.For):
        return 'for ' + _plain(s.target)
    if isinstance(s, (ast.While, ast.If)):
        return f'{type(s).__name__.lower()} {ast.unparse(s.test)}'
    return type(s).__name__.lower()


def _simple(s):
    """A simple statement as (prefix, body); the caller wraps it."""
    if isinstance(s, ast.Assign):
        return ''.join(bare(t) + ' = ' for t in s.targets), bare(s.value)
    if isinstance(s, ast.AugAssign):
        return f'{bare(s.target)} {_AUG[type(s.op)]}= ', expr(s.value)
    if isinstance(s, ast.Expr):
        return '', expr(s.value)
    if isinstance(s, ast.Return):
        return ('return ', bare(s.value)) if s.value is not None else ('return', '')
    if isinstance(s, ast.Assert):
        assert s.msg is None
        return 'assert ', expr(s.test)
    if isinstance(s, (ast.Continue, ast.Break, ast.Pass)):
        return type(s).__name__.lower(), ''
    raise ValueError(f'statement not laid out: {type(s).__name__}')


class _Comments:
    """COMMENTS looked up by statement key: '<scope>: <head>' (scope = the
    enclosing function's role, 'main' at module level; the n-th repeat of a
    key gets ' #n'), or a function's role.  A key ending in '...' matches by
    prefix.  Every COMMENTS key must match exactly one statement."""

    def __init__(self):
        self.hits = {k: 0 for k in COMMENTS}
        self.seen = {}
        self.keys = []

    def key(self, s, scope):
        if isinstance(s, ast.FunctionDef):
            k = s.name
        else:
            k = f'{scope}: {_head(s)}'
        n = self.seen[k] = self.seen.get(k, 0) + 1
        k = k if n == 1 else f'{k} #{n}'
        self.keys.append(k)
        return k

    def text(self, k):
        found = [c for c in COMMENTS if c == k or (c.endswith('...') and k.startswith(c[:-3]))]
        assert len(found) <= 1, f'statement {k!r} matches several comments: {found}'
        if found:
            self.hits[found[0]] += 1
            return COMMENTS[found[0]]
        return None

    def check(self):
        bad = {k: n for k, n in self.hits.items() if n != 1}
        assert not bad, f'comments that match no statement or several: {bad}'


def comment_lines(text, depth):
    """A comment text reflowed to the width left at its depth.  Paragraphs:
    a heading ('---- ' up to a line ending in '----'), a list item ('  - ',
    continued by lines indented four spaces; a hanging indent), running text;
    a blank line is kept.  A line end after a full stop becomes two spaces."""
    paras, cur = [], None

    def close():
        nonlocal cur
        if cur:
            paras.append(cur)
        cur = None

    for ln in text.strip('\n').split('\n'):
        if not ln.strip():
            close()
            paras.append(['blank', ''])
            continue
        if ln.startswith('---- '):
            close()
            cur = ['head', ln.strip()]
        elif ln.startswith('  - '):
            close()
            cur = ['item', ln.strip()]
        elif cur is None or (cur[0] == 'item' and not ln.startswith('    ')):
            close()
            cur = ['text', ln.strip()]
        else:
            cur[1] += ('  ' if cur[1].endswith('.') else ' ') + ln.strip()
        if cur[0] == 'head' and cur[1].endswith('----'):
            close()
    close()
    width, out = WIDTH - len(INDENT) * depth - 2, []
    for kind, body in paras:
        if kind == 'blank':
            out.append('')
            continue
        first, rest = ('  ', '    ') if kind == 'item' else ('', '')
        out += textwrap.wrap(body, width, initial_indent=first, subsequent_indent=rest,
                             break_long_words=False, break_on_hyphens=False)
    return [INDENT * depth + ('# ' + ln).rstrip() for ln in out]


def _emit(role_body, long_body, depth, scope, notes, out):
    for rs, ls in zip(role_body, long_body):
        k = notes.key(rs, scope)
        text = notes.text(k)
        if depth == 0:
            out += [''] * (2 if isinstance(rs, ast.FunctionDef) or text else 1)
        if text:
            out += comment_lines(text, depth)
        if isinstance(rs, ast.FunctionDef):
            out.append(INDENT * depth + f'def {ls.name}({", ".join(a.arg for a in ls.args.args)}):')
            _emit(rs.body, ls.body, depth + 1, rs.name, notes, out)
        elif isinstance(rs, (ast.If, ast.While)):
            out += wrap(f'{type(ls).__name__.lower()} ', expr(ls.test), ':', depth)
            _emit(rs.body, ls.body, depth + 1, scope, notes, out)
            if rs.orelse:
                out.append(INDENT * depth + 'else:')
                _emit(rs.orelse, ls.orelse, depth + 1, scope, notes, out)
        elif isinstance(rs, ast.For):
            assert not rs.orelse
            out += wrap(f'for {bare(ls.target)} in ', expr(ls.iter), ':', depth)
            _emit(rs.body, ls.body, depth + 1, scope, notes, out)
        elif isinstance(rs, ast.Try):
            assert not rs.orelse and not rs.finalbody
            out.append(INDENT * depth + 'try:')
            _emit(rs.body, ls.body, depth + 1, scope, notes, out)
            for rh, lh in zip(rs.handlers, ls.handlers):
                assert rh.type is None and rh.name is None, 'only a bare except is laid out'
                out.append(INDENT * depth + 'except:')
                _emit(rh.body, lh.body, depth + 1, scope, notes, out)
        else:
            prefix, body = _simple(ls)
            lines = wrap(prefix, body, '', depth)
            got = ast.parse('\n'.join(x[len(INDENT) * depth:] for x in lines)).body
            assert len(got) == 1 and ast.dump(got[0]) == ast.dump(ls), \
                f'layout changed a statement: {ast.unparse(ls)!r}'
            out += lines


def role_dump(long_text):
    """The ast of a long form without its shared block, every long name mapped
    back to its role (Name, arg, def) -- requirement B's left side."""
    inverse = {v: k for k, v in T.LONG_NAMES.items()}
    tree = ast.parse(T.drop_shared(long_text))
    for n in ast.walk(tree):
        if isinstance(n, ast.Name) and n.id in inverse:
            n.id = inverse[n.id]
        elif isinstance(n, ast.arg) and n.arg in inverse:
            n.arg = inverse[n.arg]
        elif isinstance(n, ast.FunctionDef) and n.name in inverse:
            n.name = inverse[n.name]
    return ast.dump(tree)


def generate(keys=None):
    """The long form's text (and, with keys a list, the statement keys)."""
    role_src = T.drop_shared(T.TEMPLATE)
    long_src = T.rename(role_src, T.LONG_NAMES)
    role_tree, long_tree = ast.parse(role_src), ast.parse(long_src)
    out = HEADER.strip('\n').split('\n') + [''] + SHARED_NOTE.strip('\n').split('\n')
    out += T.shared_block(T.TEMPLATE).rstrip('\n').split('\n')
    notes = _Comments()
    _emit(role_tree.body, long_tree.body, 0, 'main', notes, out)
    if keys is not None:
        keys += notes.keys
        return None
    notes.check()
    text = '\n'.join(out) + '\n'
    assert not [ln for ln in text.split('\n') if ln != ln.rstrip()], 'trailing space'
    assert T.shared_block(text) == T.shared_block(T.TEMPLATE), 'the shared block moved'
    assert role_dump(text) == ast.dump(role_tree), 'the long form is not the template (B)'
    return text


def main():
    if '--keys' in sys.argv:
        keys = []
        generate(keys)
        print('\n'.join(keys))
        return
    text = generate()
    if '--check' in sys.argv:
        same = os.path.exists(OUT) and open(OUT, encoding='ascii').read() == text
        print(f'{OUT}: {"the generator\'s output" if same else "DIFFERS from the generator\'s output"}')
        sys.exit(0 if same else 1)
    with open(OUT, 'w', encoding='ascii', newline='\n') as f:
        f.write(text)
    print(f'wrote {OUT} ({len(text.splitlines())} lines)')


if __name__ == '__main__':
    main()
