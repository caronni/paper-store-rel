# The loader's decoder d (cm2 v2), verbatim as the print of record's
# bootstrap/loader/a.py defines it: d(x, n, r) -> the n bytes coded in the
# integer x, the model first trained on the bits of the primer r.  The
# typed chain drops this block: a.py writes b.py as the opening of its own
# text (its check, alphabet and d) followed by the reader without the
# block, so the typed reader calls a.py's d and never defines one; the
# block is here only so that the file runs on its own.  It is the loader's
# text, not the reader's: kept as it is, short names and all.
#--- shared with the loader (not typed) ---
def d(x,n,r):
 z=[256**q-1 for q in(0,1,2,3,4,6,8,12,16)]
 m,t,h=len(r),{},0
 for i in range(m+n):
  u=1
  for j in range(8):
   g=[t.setdefault((h&q,u),[0,0])for q in z]
   p=[1+sum(c[y]<<q+(c[1-y]<1)for(q,c)in enumerate(g))for y in(0,1)]
   s=sum(p)
   if i<m:y=r[i]>>7-j&1
   else:o=x%s;y=o>=p[0];x=x//s*p[y]+o-p[0]*y
   for c in g:c[y],c[1-y]=c[y]+1,min(c[1-y],c[1-y]//4+2)
   u=2*u+y
  h=h<<8|u&255
 return h.to_bytes(m+n,'big')[m:]
#--- end shared ---


# ---- input ----
# A frame file -> (width, height, pixels), one byte per pixel, row by row, 0 =
# black.  The file is read as a P5 PGM: width and height are the second and
# third whitespace-separated fields of its first 64 bytes, the image is its
# last width * height bytes (no comment in the header and a maxval of 255
# assumed; the 'P5' itself is not checked), returned with one more image's
# worth of mid-grey (128) appended: the padding grey_at reads past the frame's
# edges.  A file that cannot be opened raises, and so, somewhere along the way,
# does a file that is not a PGM (a typed 0/1 grid given directly answers
# 'cannot read', measured); the main loop reports it.  The loupe's grid goes
# through grid_to_pgm.py first.
def load_frame(file_name):
    file_bytes = open(file_name, 'rb').read()
    pgm_width, pgm_height = [
        int(pgm_field) for pgm_field in file_bytes[:64].split()[1:3]
    ]
    return (
        pgm_width,
        pgm_height,
        file_bytes[len(file_bytes) - pgm_height * pgm_width:]
        + pgm_height * bytes([128]) * pgm_width
    )


# Step 5's refinement: the offset (1/16 px) that best centres a block on its 68
# timing modules, added into the block's position in place (the walk's block
# moves; nothing is returned).  The score of an offset is the frame score of a
# copy of the block shifted by it -- timing_score, the sum over the timing
# modules of the grey value times +1 at even dx + dy and -1 at odd -- times 1 -
# 2 * phase: so +1 where the module should be white, -1 where it should be ink
# (the block's phase).  The module positions add the block's position outside
# the floor division (module_position), so the shifted copy's spots are the
# block's own plus the offset exactly.  A 3 x 3 search around the best offset
# so far, from (0, 0), at steps of 1/2, 1/4, 1/8 and 1/16 module (pitch >> 5 to
# pitch // 256 in 1/16 px).
def fit_centre(fit_block, fit_pitch):
    offset_x = offset_y = 0
    for step in fit_pitch >> 5, fit_pitch >> 6, fit_pitch >> 7, fit_pitch >> 8:
        # max() takes the largest (score, nearness, dx, dy), nearness = -(|dx -
        # offset_x| + |dy - offset_y|) against the offset before this step: an
        # exact tie in score goes to the candidate nearest the current estimate
        # (the centre, then the four at one step, then the corners), then to
        # the larger dx, then the larger dy (fix0, ruling 47: the old tie to
        # the largest offset left blocks unread where scores are exactly flat,
        # on synthetic frames; axes/JUDGE-2026-10-22.md).  The score and the
        # nearness are dropped.
        fit_score, fit_nearness, offset_x, offset_y = max(
            (
                timing_score(
                    [fit_block[0] + try_x, fit_block[1] + try_y]
                    + fit_block[2:]
                ) * (1 - 2 * fit_block[4]),
                -abs(try_x - offset_x) - abs(try_y - offset_y),
                try_x,
                try_y
            )
            for try_x in (offset_x - step, offset_x, offset_x + step)
            for try_y in (offset_y - step, offset_y, offset_y + step)
        )
    # the best offset moves the block itself
    fit_block[0] += offset_x
    fit_block[1] += offset_y


# ---- the check ----
# CRC-32 (R2-FORMAT "CRC-32"), the one check of the page: blocks, header and
# data.  The register starts at ffffffff (2 ** 32 - 1); for each byte, xor it
# in, then eight times shift right, xoring 0xEDB88320 when the bit shifted out
# is 1; the CRC is the register xor ffffffff.
def crc32(crc_input):
    register = 2 ** 32 - 1
    for crc_byte in crc_input:
        register = crc_byte ^ register
        for crc_shift in range(8):
            register = register >> 1 ^ 0xEDB88320 * (register & 1)
    return register ^ 2 ** 32 - 1


# ---- a block's geometry ----
# The position (1/16 px) of module (dx, dy) of a block: its centre + (A * dx +
# B * dy) / 17, floor division per axis.
def module_position(placed_block, module_dx, module_dy):
    return (
        placed_block[0] + (
            placed_block[2][0] * module_dx + placed_block[3][0] * module_dy
        ) // 17,
        placed_block[1] + (
            placed_block[2][1] * module_dx + placed_block[3][1] * module_dy
        ) // 17
    )


# ---- the page's geometry (R2-FORMAT "Blocks", "Bullseye blocks", "Timing
# lattice"), as module offsets (dx, dy) from a block's centre module ----
# The bullseye: its 177 modules with q = dx*dx + dy*dy < 57, as (dx, dy, ink).
# ring_step counts the i in 0..6 with i * i + i < q, which is the integer
# nearest the root of q (R2-FORMAT's ring d); ink iff it is even.  For q <= 42
# that is the ring pattern (ink exactly for the q in {0, 4, 5, 13, 16, 17, 18,
# 20, 32, 34, 36, 37, 40, 41}); 43 <= q <= 56 is the quiet ring, d = 7, white.
# Used only to confirm a bullseye candidate (find_bullseyes).
ring_modules = [
    (
        ring_dx,
        ring_dy,
        sum(
            ring_dx * ring_dx + ring_dy * ring_dy
            > ring_step * ring_step + ring_step
            for ring_step in range(7)
        ) & 1 < 1
    )
    for ring_dy in range(-7, 8)
    for ring_dx in range(-7, 8)
    if ring_dx * ring_dx + ring_dy * ring_dy < 57
]


# A block's 256 data modules in raster order (dy outer, dx inner, both in
# -8..7): the order of a data block's bits, MSB first (byte k = modules 8k to
# 8k + 7).
data_modules = [
    (data_dx, data_dy) for data_dy in range(-8, 8) for data_dx in range(-8, 8)
]


# A bullseye block's header modules (q >= 57) in the same raster order; the
# first 68 carry the header, MSB first: bits 0-15 the data's length, 16-47 its
# CRC-32, 48-67 the CRC-32 of the six bytes above modulo 2 ** 20.  The 11 not
# taken lie in the block's bottom row, which is white.
header_modules = [
    (header_dx, header_dy)
    for header_dx, header_dy in data_modules
    if header_dx * header_dx + header_dy * header_dy > 56
][:68]


# The 68 timing modules around a block, as (dx, dy, (dx + dy) % 2): rows -9 and
# 8 (18 modules each), columns -9 and 8 (16 each); 34 of each parity.  The
# timing frame lies 9 modules out on the left and top of the centre and 8 on
# the right and bottom: that asymmetry is what tells the quarter turn
# (pose_frame).
timing_modules = [
    (timing_dx, timing_dy, timing_dx + timing_dy & 1)
    for timing_dy in range(-9, 9)
    for timing_dx in range(-9, 9)
    if {timing_dx, timing_dy} & {-9, 8}
]


# ---- step 3: the pose ----
# A seed at (x, y) for a frame rotated by rotation / 4096 radian and turned by
# quarter_turns: cosine = 4096 - (rotation ** 2 >> 13) (4096 x the cosine, to
# second order) and rotation itself as 4096 x the sine; A = 17 modules along
# +dx = (17 p cos, 17 p sin), B = 17 modules along +dy = (-17 p sin, 17 p cos),
# each product >> 16 so that p (1/256 px per module) x 4096 comes out in 1/16
# px; then turned: each quarter turn takes (A, B) to (B, -A).  -> [x, y, A, B].
def seed_axes(seed_x, seed_y, seed_pitch, rotation, quarter_turns):
    cosine = 4096 - (rotation * rotation >> 13)
    step_a = [17 * seed_pitch * cosine >> 16, 17 * seed_pitch * rotation >> 16]
    step_b = [
        -17 * seed_pitch * rotation >> 16, 17 * seed_pitch * cosine >> 16
    ]
    for turn_index in range(quarter_turns):
        step_a, step_b = step_b, [-step_a[0], -step_a[1]]
    return [seed_x, seed_y, step_a, step_b]


# The grey value at the centre of each of a block's 18 x 18 modules (dx, dy in
# -9..8: the 256 data modules and the timing frame), and the block's threshold,
# midway between the 9th darkest and the 9th brightest of its 68 timing modules
# (R2-FORMAT step 6).  -> (greys by (dx, dy), threshold).
def sample_block(sampled_block):
    block_grey = {
        (cell_dx, cell_dy): grey_at(
            *module_position(sampled_block, cell_dx, cell_dy)
        )
        for cell_dy in range(-9, 9)
        for cell_dx in range(-9, 9)
    }
    timing_sorted = sorted(
        block_grey[sorted_dx, sorted_dy]
        for sorted_dx, sorted_dy, sorted_parity in timing_modules
    )
    return block_grey, timing_sorted[8] + timing_sorted[59] >> 1


# The grey value at (x, y) in 1/16 px: bilinear between the four pixels around
# the point (pixel i sits at 16 * i).  No clamp: load_frame appends one image
# of mid-grey (128) to the pixels, so no point leaves the buffer -- left or
# right of the frame it reads the adjacent row, below the last row the padding,
# above the first row a negative index wraps to the buffer's end and reads the
# padding.  Every point read comes from a bullseye found in the frame or a
# block kept 10 modules inside it; the deepest overrun measured is about 12
# rows, the padding a whole image (the grey padding, 2026-10-23,
# changeset/RESULTS-2026-10-22.md sections 19-20; until then the point was
# clamped to [0, 16 * width - 17] x [0, 16 * height - 17] and read the pixels
# at the frame's edge).  Reads the frame globals frame_width and frame_pixels.
# -> 0..255.
def grey_at(at_x, at_y):
    frac_x, frac_y, pixel_index = (
        at_x & 15, at_y & 15, (at_y >> 4) * frame_width + (at_x >> 4)
    )
    return (
        (
            frame_pixels[pixel_index] * (16 - frac_x)
            + frame_pixels[pixel_index + 1] * frac_x
        ) * (16 - frac_y)
        + (
            frame_pixels[pixel_index + frame_width] * (16 - frac_x)
            + frame_pixels[pixel_index + frame_width + 1] * frac_x
        ) * frac_y
        >> 8
    )


# The timing score of a seed: the sum over its 68 timing modules of the grey
# value x (+1 at even dx + dy, -1 at odd).  Its magnitude says how well the
# seed's axes fit the timing frame; its sign gives the phase (negative: the
# even modules are ink, phase 1).
def timing_score(scored_seed):
    return sum(
        grey_at(
            *module_position(scored_seed, score_dx, score_dy)
        ) * (1 - 2 * score_parity)
        for score_dx, score_dy, score_parity in timing_modules
    )


# ---- step 2: the bullseyes (R2-FORMAT "Decoding") ----
# The bullseyes of the binarised frame.  Every pixel row is searched for combs.
# A comb within 6 modules (|dx| + |dy|) of a bullseye already found is skipped.
# Otherwise the column through the comb's centre pixel is searched, from 12
# modules + 2 px above the row to as far below, for the comb whose centre is
# nearest the row; it must lie within one module of the row.  The candidate's
# centre is (the row comb's centre, the column comb's), its pitch the mean of
# the two combs' spans.  The whole block must lie in the frame: in 1/16 px, x
# and y at least pitch // 2 (8 modules), x at most 16 * width - 32 - pitch // 2
# and y likewise (16 * width - 32 is pixel width - 2).  And 75 % of the 177
# ring modules, each read on the binarised frame at the pixel nearest the
# centre + (dx, dy) modules, must match the rings.  -> [(ring hits, x, y,
# pitch)] in the order found (row by row; not sorted), x and y in 1/16 px, the
# pitch in 1/256 px per module.
def find_bullseyes(frame_bits):
    found = []
    for pixel_row in range(frame_height):
        # row_centre_x4: 4 x the comb's centre in px; row_span_x2: 2 x its
        # span, so 24 modules in px.
        for row_centre_x4, row_span_x2 in find_combs(
            frame_bits[
                frame_width * pixel_row:frame_width * pixel_row + frame_width
            ]
        ):
            # the comb's centre pixel, rounded: the column searched next
            centre_column = row_centre_x4 + 2 >> 2
            # |dx| + |dy| in 1/256 px against 6 x the pitch of a bullseye
            # already found: within 6 modules of it, skip
            if [
                known_bullseye
                for known_bullseye in found
                if 16 * abs(known_bullseye[1] - 4 * row_centre_x4)
                + 16 * abs(known_bullseye[2] - 16 * pixel_row)
                < 6 * known_bullseye[3]
            ]:
                continue
            # the column window: from 12 modules + 2 px above the row to as far
            # below (row_span_x2 // 2 is 12 modules in px)
            window_top, window_end = (
                max(0, pixel_row - row_span_x2 // 2 - 2),
                min(frame_height, pixel_row + row_span_x2 // 2 + 3)
            )
            # the column comb nearest the row: column_miss = |its centre - the
            # row| in quarter px; (row_span_x2, 0, 0) when the column has none,
            # which the next test refuses
            column_miss, column_centre_x4, column_span_x2 = min(
                [
                    (
                        abs(cand_centre_x4 - 4 * (pixel_row - window_top)),
                        cand_centre_x4,
                        cand_span_x2
                    )
                    for cand_centre_x4, cand_span_x2 in find_combs(
                        frame_bits[
                            frame_width * window_top + centre_column:
                            frame_width * window_end:
                            frame_width
                        ]
                    )
                ]
                + [(row_span_x2, 0, 0)]
            )
            # more than one module (row_span_x2 / 6 quarter px) from the row:
            # skip
            if row_span_x2 < 6 * column_miss:
                continue
            # the pitch 16 x (row_span_x2 + column_span_x2) / 3 = 256 x the
            # mean px per module; the centre in 1/16 px
            pitch, centre_x, centre_y = (
                (row_span_x2 + column_span_x2) * 16 // 3,
                4 * row_centre_x4,
                4 * (column_centre_x4 + 4 * window_top)
            )
            # the whole block not in the frame: skip
            if (
                min(centre_x, centre_y) < pitch // 2
                or centre_x > 16 * frame_width - pitch // 2 - 32
                or centre_y > 16 * frame_height - pitch // 2 - 32
            ):
                continue
            # the ring modules that match the rings
            ring_hits = sum(
                frame_bits[
                    (centre_y + (check_dy * pitch >> 4) + 8 >> 4) * frame_width
                    + (centre_x + (check_dx * pitch >> 4) + 8 >> 4)
                ] == check_ink
                for check_dx, check_dy, check_ink in ring_modules
            )
            # 75 % or more: a bullseye
            if 4 * ring_hits >= len(ring_modules) * 3:
                found += [(ring_hits, centre_x, centre_y, pitch)]
    return found


# ---- step 5: the walk, with step 6's reads ----
# Breadth first from every seed at once.  queue starts as the frame's seeds and
# grows while it is iterated: it is the walk's queue.  walk_pitch is the first
# bullseye's; it sets the cell size, the frame check and fit_centre's steps for
# every block.  For each queued block, its centre as predicted by the block
# that queued it:
#   - a block whose predicted centre falls in a cell (5 x 5 modules of the
#     frame grid) reached before is skipped, else the cell is marked; this also
#     bounds the walk (the cells are finite);
#   - a block whose predicted centre lies within 10 modules of the frame's edge
#     is skipped, and nothing is queued from it;
#   - a block other than the seed's bullseye (block_row or block_column not 0)
#     is refined on its timing modules (fit_centre moves it); then each of its
#     steps A and B is re-measured as the vector from its placed neighbour one
#     block nearer the seed along that axis, if that neighbour was placed and
#     the block is off the seed's own column (for A) or row (for B);
#   - a block other than the bullseye is read (read_data_block); a read that
#     passes its CRC-32 is kept;
#   - the walk passes through the bullseye, a block whose read passed its
#     CRC-32 and a white slot: such a block is placed and its four neighbours
#     are queued.  A block whose CRC-32 fails is a wall the walk goes round
#     (the CRC-gated walk, ruling 45; the timing-correlation test of the print
#     of record's reader is gone).
# The bullseye block itself is neither refined nor read.  -> the accepted
# blocks (28 bytes each), in the order read.
def walk_blocks(walk_pitch, queue):
    seen_cells = {}
    # cell_size: 5 modules in 1/16 px (5 x pitch / 16); placed: the blocks
    # walked through, by (seed_number, block_row, block_column)
    cell_size, placed = 5 * walk_pitch >> 4, {}
    accepted_blocks = []
    for current in queue:
        # the cell of the predicted centre (before any refinement)
        cell_x = current[0] // cell_size
        cell_y = current[1] // cell_size
        if (cell_x, cell_y) in seen_cells:
            continue
        seen_cells[cell_x, cell_y] = 1
        # the frame check on the block centre: closer than 10 modules (5 x
        # pitch >> 3 in 1/16 px) to the left or top edge, or to 16 x size - 32
        # (pixel size - 2) on the right or bottom: skip
        if (
            min(
                current[0],
                current[1],
                16 * frame_width - 32 - current[0],
                16 * frame_height - 32 - current[1]
            )
            < 5 * walk_pitch >> 3
        ):
            continue
        seed_number, block_row, block_column = current[5]
        # not the bullseye: refine; then re-measure A (index 2, counted by
        # block_column) and B (index 3, counted by block_row) from the placed
        # neighbour one step nearer the seed; sign = 0 on the seed's own column
        # or row keeps the step the block was queued with
        if block_row or block_column:
            fit_centre(current, walk_pitch)
            for axis, along in (2, block_column), (3, block_row):
                sign = (along > 0) - (along < 0)
                neighbour = placed.get(
                    (
                        seed_number,
                        block_row - sign * (axis > 2),
                        block_column - sign * (axis < 3)
                    )
                )
                if neighbour and sign:
                    current[axis] = [
                        sign * (current[0] - neighbour[0]),
                        sign * (current[1] - neighbour[1])
                    ]
        # 0 for the bullseye (not read); for any other block its 28 bytes, b''
        # for a white slot, None when its CRC-32 fails
        block_read = (block_row or block_column) and read_data_block(current)
        if block_read:
            accepted_blocks += [block_read]
        # walk through it: place it and queue its four neighbours, direction 0
        # / 1 = +A / -A (block_column + 1 / - 1), 2 / 3 = +B / -B (block_row +
        # 1 / - 1), the phase flipped (a block is 17 modules, an odd number)
        if block_read != None:
            placed[seed_number, block_row, block_column] = current
            queue += [
                [
                    current[0]
                    + direction_sign * current[2 + direction // 2][0],
                    current[1]
                    + direction_sign * current[2 + direction // 2][1],
                    current[2],
                    current[3],
                    1 - current[4],
                    (
                        seed_number,
                        block_row + direction_sign * (direction > 1),
                        block_column + direction_sign * (direction < 2)
                    )
                ]
                for direction in range(4)
                for direction_sign in [1 - 2 * (direction & 1)]
            ]
    return accepted_blocks


# The bullseye's signature along one line of the binarised frame (1 = ink).
# run_starts: where each run of equal bits starts (0 first; the line's length
# appended).  A comb is 13 consecutive runs, ink first and last (seven ink, six
# white), with
#   - the centres of its first and last ink run at least 12 px apart (span_x2 >
#     23: one px per module or more);
#   - white of at least a quarter module before the first and after the last
#     ink run (96 * white >= span_x2);
#   - the centres of runs 1-4 and 8-11 on the grid the two outer ink runs set
#     (run k at k twelfths of the span) within 0.3 module + 0.6 px.
# Runs 5-7 (the centre dot and the white beside it) are not measured, but runs
# are counted by index, so the centre dot must survive as a run of its own.
# Run centres, not edges, are compared: they do not move with the threshold.
# -> [(4 x the comb's centre, 2 x its span)], in px along the line with pixel k
# at k.
def find_combs(bit_line):
    run_starts, run_bit, edge_at = [0], bit_line[0], 0
    while edge_at >= 0:
        edge_at = bit_line.find(1 - run_bit, edge_at)
        if edge_at > 0:
            run_bit, run_starts = 1 - run_bit, run_starts + [edge_at]
    run_starts += [len(bit_line)]
    # For every ink run that has a run before it (ink_run indexes run_starts):
    # first_centre_x2 = its start + its end = 2 x its centre + 1, and span_x2 =
    # 2 x the distance from its centre to the centre of the ink run 12 runs on.
    return [
        (
            first_centre_x2
            + run_starts[ink_run + 12]
            + run_starts[ink_run + 13]
            - 2,
            span_x2
        )
        for ink_run in range(1 + bit_line[0], len(run_starts) - 14, 2)
        for first_centre_x2, span_x2 in [
            (
                run_starts[ink_run] + run_starts[ink_run + 1],
                run_starts[ink_run + 12]
                + run_starts[ink_run + 13]
                - run_starts[ink_run]
                - run_starts[ink_run + 1]
            )
        ]
        if span_x2 > 23
        and min(
            run_starts[ink_run] - run_starts[ink_run - 1],
            run_starts[ink_run + 14] - run_starts[ink_run + 13]
        ) * 96 >= span_x2
        and max(
            abs(
                12 * (
                    run_starts[ink_run + inner_offset + 6]
                    + run_starts[ink_run + inner_offset + 7]
                    - first_centre_x2
                )
                - (inner_offset + 6) * span_x2
            )
            for inner_offset in (-5, 5, -4, 4, -3, 3, -2, 2)
        ) <= (3 * span_x2 + 144) // 10
    ]


# Step 6 for one data block: sample it; when more than 3 of its 256 data
# modules are darker than its threshold (the raw grey value, not sharpened),
# read and check it -> its 28 bytes (2 of chunk index, 26 of chunk) or None
# when no read passes; else b'': a block with three or fewer ink modules is a
# white slot, not tried, and the walk passes through it.
def read_data_block(data_block):
    data_grey, data_threshold = sample_block(data_block)
    return (
        read_checked(data_grey, data_threshold, data_modules, 32)
        if sum(
            data_grey[ink_dx, ink_dy] < data_threshold
            for ink_dx, ink_dy in data_modules
        ) > 3
        else b''
    )


# ---- step 6, and step 4's header: read and check ----
# The bits of the given modules, MSB first, checked.  A module reads 1 (ink)
# when its grey value sharpened by half its 4-neighbour Laplacian -- grey -
# ((the 4 neighbours' sum - 4 * grey) >> 1) -- is below the threshold.  The
# last check_bits bits must equal the CRC-32, modulo 2 ** check_bits, of the
# global header followed by the bytes before them.  A data block (256 modules,
# 32 check bits) is checked against the payload's six header bytes (R2-FORMAT
# "Data blocks": a block validates only against its own payload), plain first,
# then with each single module flipped, from the last module (bit 0) to the
# first.  The header (68 modules, 20 check bits) is read only while no header
# is known: the global header is b'' then, so the check is the CRC-32 of its
# six bytes modulo 2 ** 20; it is read plain only.  -> the bytes before the
# check (28 for a data block, 6 for the header), or None.
def read_checked(grey_of, threshold, modules, check_bits):
    module_count = len(modules)
    plain_read = int(
        ''.join(
            '01'[
                threshold - grey_of[read_dx, read_dy] + (
                    grey_of[read_dx - 1, read_dy]
                    + grey_of[read_dx + 1, read_dy]
                    + grey_of[read_dx, read_dy - 1]
                    + grey_of[read_dx, read_dy + 1]
                    - 4 * grey_of[read_dx, read_dy]
                    >> 1
                )
                > 0
            ]
            for read_dx, read_dy in modules
        ),
        2
    )
    for flip in (
        [0]
        + [
            1 << flip_bit
            for flip_bit in range(module_count * (check_bits > 20))
        ]
    ):
        candidate = plain_read ^ flip
        if (
            crc32(
                header
                + (candidate >> check_bits).to_bytes(
                    (module_count - check_bits) // 8
                )
            ) % 2 ** check_bits
            == candidate % 2 ** check_bits
        ):
            return (candidate >> check_bits).to_bytes(
                (module_count - check_bits) // 8
            )


# Steps 1-4 for the frame in the globals.  -> ((walk_pitch, seeds), header):
# the first bullseye's pitch (0 when there is none), the seeds, and the
# session's header -- read here when none was known; b'' while none is.
def pose_frame():
    # Step 1: binarise with one threshold midway between the darkest and the
    # brightest of every 97th pixel (a grey value below it maps to 1, ink); it
    # serves only the bullseye search.  The sample runs over the padding too,
    # and 128 moves neither extreme on a frame with a value at or below 128 and
    # one at or above it.  Step 2: the bullseyes.
    bullseyes = find_bullseyes(
        frame_pixels.translate(
            bytes(
                grey_level < binarise_threshold
                for binarise_threshold in [
                    min(frame_pixels[::97]) + max(frame_pixels[::97]) >> 1
                ]
                for grey_level in range(256)
            )
        )
    )
    # Step 3: one rotation and one quarter turn for the whole frame: rotation r
    # / 4096 radian with r = -640..640 in steps of 64 (0.9 degree steps up to
    # 8.95 degrees), turn 0..3; the pair whose seeds, built from each
    # bullseye's comb centre and pitch, give the largest sum of |timing score|
    # over all bullseyes.  An exact tie goes to the smallest |r| (ruling 47),
    # then the larger r, then the larger turn; with no bullseye every score is
    # 0 and the pair is (0, 3).  The score and the tie key are dropped.
    pose_score, pose_nearness, frame_rotation, frame_turns = max(
        (
            sum(
                abs(
                    timing_score(
                        seed_axes(
                            cand_x, cand_y, cand_pitch, try_rotation, try_turns
                        )
                    )
                )
                for cand_hits, cand_x, cand_y, cand_pitch in bullseyes
            ),
            -abs(try_rotation),
            try_rotation,
            try_turns
        )
        for try_rotation in range(-640, 641, 64)
        for try_turns in range(4)
    )
    seeds = []
    # Each bullseye becomes a seed: its comb centre (not refined), the frame's
    # axes at its own pitch, its phase from the sign of its timing score, and
    # (its index, 0, 0).
    for hits, bull_x, bull_y, bull_pitch in bullseyes:
        seed = seed_axes(
            bull_x, bull_y, bull_pitch, frame_rotation, frame_turns
        )
        seeds += [seed + [int(timing_score(seed) < 0), (len(seeds), 0, 0)]]
    # Step 4: a known header stands and no header is read; otherwise the header
    # modules of each seed are read in turn, at the seed as placed (its own
    # timing threshold, the plain read, the 20-bit check), until one passes.
    header_read = header
    for seed in seeds:
        header_read = (
            header_read
            or read_checked(*sample_block(seed), header_modules, 20)
        )
    return (bullseyes[0][3] if bullseyes else 0, seeds), header_read or header


# ---- the session ----
# chunks: chunk index -> its 26 bytes, pooled over every frame and page, the
# last read of an index winning.  header: the payload's six header bytes (the
# data's length and CRC-32), b'' until the first header passes its check, then
# fixed for the session: later frames are checked against it and their own
# headers are not read.  done: 0, then the data's CRC-32 test.  chunk_count: N
# = ceil(length / 26), '?' until a header is known.
header, done, chunks, chunk_count = b'', 0, {}, '?'


# one frame per pass, until done
while done < 1:
    # 0 before the prompt: at the end of input, input() raises and frame_name
    # stays 0; an empty line (or spaces) makes load_frame('') raise; either way
    # 'not frame_name' ends the loop quietly
    frame_name = 0
    # Any exception while the frame is loaded, posed or walked prints 'cannot
    # read' alone and the frame adds no chunk (the walk's blocks are pooled
    # only once it returns); the done test runs again with the next frame.  The
    # bare except also catches Ctrl-C: during a frame it skips the frame, at
    # the prompt it ends the run.  A header that pose_frame returned stands
    # even if the walk then raises.
    try:
        frame_name = input('file: ').strip()
        # the frame globals that grey_at, find_bullseyes, walk_blocks and
        # pose_frame read
        frame_width, frame_height, frame_pixels = load_frame(frame_name)
        posed, header = pose_frame()
        # the bullseyes are counted before the walk extends the seed list
        bullseyes_found = len(posed[1])
        # blocks are checked against the header: none known yet, no walk.
        # pool: the chunk index is the block's first two bytes, big-endian (the
        # default byte order of int.from_bytes from Python 3.11 on); the chunk
        # is its other 26
        for block in walk_blocks(*posed) if header else []:
            chunks[int.from_bytes(block[:2])] = block[2:]
        # step 7: when chunks 0..N-1 are all held, the data are the chunks
        # joined and cut to the length, and done is whether their CRC-32 equals
        # the header's (bytes 2-5)
        if header:
            data_length = int.from_bytes(header[:2])
            chunk_count = (data_length + 25) // 26
            if (
                sum(held_index in chunks for held_index in range(chunk_count))
                == chunk_count
            ):
                data = b''.join(
                    chunks[chunk_index] for chunk_index in range(chunk_count)
                )[:data_length]
                done = crc32(data) == int.from_bytes(header[2:])
        # The progress line (ruling 56 as amended, 2026-10-22): 'N@ H/T', e.g.
        # '9@ 500/557'.  N counts the bullseyes found in the frame (none: shoot
        # again; many and no new chunks: move the camera); '@' is the target
        # mark, a literal in the format string since 2026-10-23 (the owner's
        # ruling: count_reader.py admits an '@' inside a string literal; on
        # 2026-10-22 it was printed as %c of 64).  H counts every chunk index
        # held (a false accept carrying an index of N or more counts too); T is
        # N, '?' until a header is known.  No file name (the prompt line above
        # shows it), no blocks count, no done flag: the exit with c.py written
        # is the done signal.  Until then the line was 'NAME: N bullseyes, B
        # blocks, chunks H / T more' (or 'done'; ruling 54, before it 'blocks
        # accepted, chunks').
        print('%d@ %d/%s' % (bullseyes_found, len(chunks), chunk_count))
    except:
        if not frame_name:
            break
        # a file that cannot be read: the line 'cannot read' alone
        print('cannot read')


# Step 7, the close: the data as one big-endian integer, decoded by the
# loader's d with N2 bytes to produce and b.py's bytes (read in binary) as the
# primer; the result's CRC-32 must be B2, else AssertionError and no file; then
# c.py.  A changed b.py (other line ends, an extra newline) decodes to other
# bytes and stops at the assert.
if done:
    bundle = d(int.from_bytes(data), N2, open('b.py', 'rb').read())
    assert crc32(bundle) == B2
    open('c.py', 'wb').write(bundle)
