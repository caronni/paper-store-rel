# 1. The program's own text, as bytes: the subject of the self-dump, the
# primer of the decoder and the source of b.py's definitions.  strip() drops
# leading and trailing whitespace (so a final newline cannot matter); reading in
# text mode turns CRLF into LF (so the editor's line ends cannot matter).
program = open('a.py').read().strip().encode()

# 2. The alphabet: base 32, Crockford's 32 glyphs (no I, L, O, U), in the
# case of this print.  Nothing is folded: a look-alike typed anyway fails the
# line check and the line is retyped.  line_number is the number of the line
# expected next, number the integer the data lines spell; both start here, so
# b.py carries them too (the reader may rebind them).
number, alphabet, line_number = (0, '0123456789ABCDEFGHJKMNPQRSTVWXYZ', 1)

# 3. The check code of a line: seeded with the line number, for each byte
# add it, then multiply by 1000003; the code is bits 0..19 of the result as four
# glyphs of 5 bits, highest first.  One wrong glyph, two glyphs swapped at any
# distance or the right line at a wrong number never pass; a random wrong line
# passes with probability 1/1048576.  The reader's whole text is checked with
# the seed 0.
def check(code, text):
    for byte in text:
        code = (byte + code) * 1000003
    return ''.join((alphabet[code >> shift & 31] for shift in (15, 10, 5, 0)))

# 4. decode: cm2 v2, count mixing with a big-integer rANS decoder.  state is
# the whole coded message as ONE integer (the number the data lines spell),
# count the number of bytes to produce, primer the bytes the model learns from
# first, orders the context lengths (item 7: a parameter with a default, the
# tuple this print was searched to; the reader decodes the R2 pages with it).
# For every bit the model gives two weights, p0 and p1: bit 0 owns the slots
# [0, p0) of state % (p0 + p1), bit 1 the slots [p0, p0 + p1).  Decoding a bit:
# slot = state % total, bit = slot >= p0, state = state // total * p_bit + slot
# - p0 * bit.  state only shrinks and is 0 after the last bit.  The model: one
# counter pair per order and bit, keyed by (the last `order` bytes as one
# integer, the bits of the current byte so far behind a leading 1); p_y = 1 +
# the sum over the orders (index w) of count_y << (w + 1 if count_other is 0
# else w); after the bit count_y += 1, count_other = min(count_other,
# count_other // 4 + 2).  The primer's bits are read, not decoded: they only
# train the counters.  Two orders whose keys coincide share one pair, updated
# once for each.
def decode(state, count, primer, orders=(0, 1, 2, 3, 4, 6)):
    # the mask of the last `order` bytes of the history, per order
    masks = [256 ** order - 1 for order in orders]
    # the primer's length; the counters (empty) and the history (every byte so far
    # as one integer, 0) to start
    primer_length, history, counters = (len(primer), 0, {})
    # every byte: the primer's first, then the decoded ones
    for position in range(primer_length + count):
        # the bits of the current byte so far, behind a leading 1
        partial = 1
        # eight bits a byte, the most significant first
        for bit_index in range(8):
            # one counter pair per order, created at [0, 0]
            pairs = [counters.setdefault((history & mask, partial), [0, 0]) for mask in masks]
            # the two weights p0, p1
            weights = [1 + sum((pair[outcome] << index + (pair[outcome ^ 1] < 1) for index, pair in enumerate(pairs))) for outcome in [0, 1]]
            # a primer bit is read; a message bit is decoded out of state
            if primer_length > position:
                bit = primer[position] >> 7 - bit_index & 1
            else:
                # their sum
                total = sum(weights)
                slot = state % total
                bit = slot >= weights[0]
                state = state // total * weights[bit] + slot - weights[0] * bit
            # update every pair: count_bit + 1, the other count cut
            for counter_pair in pairs:
                counter_pair[bit] += 1
                counter_pair[1 - bit] = min(counter_pair[1 - bit] // 4 + 2, counter_pair[1 - bit])
            partial += partial + bit
        # append the finished byte to the history
        history = history << 8 | partial % 256
    # the decoded bytes, without the primer
    return history.to_bytes(primer_length + count)[primer_length:]

# 5. The self-dump: the number and the check code of every line of a.py, to
# compare with the codes printed beside the listing before any data is typed.
# The counter is the data's line counter: it ends at the listing's line
# count + 1, the number of the first data line.
for listing_line in program.splitlines():
    print(line_number, check(line_number, listing_line))
    line_number += 1

# 6. The data.  The prompt [n] asks for data line n; a line whose check fails
# is not taken and [n] comes back.  Spaces are removed first (the leaf prints
# groups of 5).  An accepted line's glyphs go into number, 5 bits each.
while line_number < 68:
    typed = input([line_number]).replace(' ', '')
    if typed[-4:] == check(line_number, typed[:-4].encode()):
        line_number += 1
        for glyph in typed[:-4]:
            number = 32 * number + alphabet.find(glyph)

# 7. Decode the reader (its length baked) with a.py's text as the primer.
reader = decode(number, 3935, program)

# Its check code must be this print's, or the program stops here with a
# traceback and writes nothing: a wrong number decodes to other bytes.
assert 'EV6F' == check(0, reader)

# 8. b.py = the definitions of a.py (2-4 above, the typed text exactly, the
# slice of its bytes) + the reader, written in binary: its bytes are the
# primer the reader hands decode() for the R2 pages.  Nothing is printed:
# silence is success.  Next: python3 b.py
open('b.py', 'wb').write(program[39:591] + reader)
