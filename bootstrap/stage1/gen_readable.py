def _role_of_target(t, inv, prefix=''):
    """The role a statement's comment hangs on: for a parallel assignment the
    first target whose role has a comment (the order of the targets is a
    searched spelling, so the first target is not stable), else the first."""
    elts = t.elts if isinstance(t, (ast.Tuple, ast.List)) else [t]
    roles = []
    for e in elts:
        while isinstance(e, ast.Subscript):
            e = e.value
        roles.append(inv.get(e.id) if isinstance(e, ast.Name) else None)
    for r in roles:
        if r and prefix + r in COMMENTS:
            return r
    return roles[0]


def _key(s, inv, depth, ctx='main'):
    prefix = f'{ctx}:' if depth else ''
    if isinstance(s, ast.FunctionDef):
        return inv.get(s.name)
    if isinstance(s, ast.For):
        return _role_of_target(s.target, inv, prefix)
    if isinstance(s, ast.While):
        return 'while'
    if isinstance(s, ast.If):
        return 'if' if depth else None
    if isinstance(s, (ast.Assign, ast.AugAssign)):
        r = _role_of_target(s.targets[0] if isinstance(s, ast.Assign) else s.target, inv, prefix)
        if r == 'Num' and depth == 0 and isinstance(s.value, ast.Call):
            return 'Num@main'
        return r
    if isinstance(s, ast.Assert):
        return 'assert'
    if isinstance(s, ast.Expr):
        return 'expr' if depth == 0 else None
    if isinstance(s, ast.Return):
        return 'return'
    return None


def _header(s):
    import copy
    c = copy.copy(s)
    c.body = [ast.Pass()]
    if hasattr(c, 'orelse'):
        c.orelse = []
    return ast.unparse(c).split('\n')[0]


def _emit(stmts, depth, inv, used, out, ctx='main'):
    for s in stmts:
        k = _key(s, inv, depth, ctx)
        if depth:
            k = f'{ctx}:{k}'
        if k in COMMENTS and k not in used:
            used.add(k)
            if k in ('Td', 'Idx'):
                used.update(('Td', 'Idx'))
            if k in ('Out', 'Num@main'):
                used.update(('Out', 'Num@main'))
            if depth == 0:
                out.append('')
            for ln in COMMENTS[k].split('\n'):
                out.append(INDENT * depth + '# ' + ln)
        if isinstance(s, (ast.For, ast.While, ast.If, ast.FunctionDef)):
            out.append(INDENT * depth + _header(s))
            inner = inv.get(s.name) if isinstance(s, ast.FunctionDef) else ctx
            _emit(s.body, depth + 1, inv, used, out, inner)
            if getattr(s, 'orelse', None):
                out.append(INDENT * depth + 'else:')
                _emit(s.orelse, depth + 1, inv, used, out, inner)
        else:
            for ln in ast.unparse(s).split('\n'):
                out.append(INDENT * depth + ln)


def role_text(edits, case, orders, N, C1, R, start, end):
    """The template with the edits, the alphabet, the tuple and the print's
    constants -- the text the typed a.py is the renaming of."""
    t = T.fill(T.apply_edits(edits), case, orders)
    for k, v in (('@N@', N), ('@C1@', C1), ('@R@', R), ('@D@', start), ('@E@', end)):
        t = t.replace(k, str(v))
    assert '@' not in t
    return t


def readable(edits, case, orders, N, C1, R, start, end):
    src = T.rename(role_text(edits, case, orders, N, C1, R, start, end), T.LONG_NAMES)
    inv = {v: k for k, v in T.LONG_NAMES.items()}
    assert len(inv) == len(T.LONG_NAMES), 'long names must be distinct'
    out = [HEADER.format(case=case).rstrip('\n')]
    saved = dict(COMMENTS)
    if 'selfdump-counter' in edits:          # the counter of the data counts the listing first
        for k in ('Td', 'Idx'):
            COMMENTS[k] += ('\nThe counter is the data\'s line counter: it ends at the listing\'s line\n'
                            'count + 1, the number of the first data line.')
    try:
        _emit(ast.parse(src).body, 0, inv, set(), out)
    finally:
        COMMENTS.clear()
        COMMENTS.update(saved)
    text = '\n'.join(out) + '\n'
    assert ast.dump(ast.parse(text)) == ast.dump(ast.parse(src)), 'layout changed the program'
    return text


def main():
    a = sys.argv[1:]
    case = a[a.index('--case') + 1] if '--case' in a else 'lower'
    d = os.path.join(os.path.dirname(HERE), 'build', 'stage1', case)
    b = json.load(open(os.path.join(d, 'build.json')))
    text = readable(b['edits'], case, tuple(b['orders']), b['N'], b['loop_bound'],
                    b['reader_code'], *b['slice'])
    open(os.path.join(d, 'readable.py'), 'w').write(text)
    print('wrote', os.path.join(d, 'readable.py'))


if __name__ == '__main__':
    main()
